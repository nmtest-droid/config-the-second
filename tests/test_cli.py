class QuietHandler(http.server.SimpleHTTPRequestHandler):
    """Suppress access logs from the local HTTP test server."""

    def log_message(self, format_string, *args):
        """Ignore request log messages generated by the test server."""
        pass


def make_service_index(root: Path, base_address: str = "packages/") -> Path:
    """Write a minimal NuGet V3 service index to a fixture directory."""
    root.mkdir(parents=True, exist_ok=True)
    index_path = root / "index.json"
    index_path.write_text(
        json.dumps(
            {
                "version": "3.0.0",
                "resources": [
                    {"@id": base_address, "@type": "PackageBaseAddress/3.0.0"}
                ],
            }
        ),
        encoding="utf-8",
    )
    return index_path


def write_nuspec(root: Path, package: str, version: str, xml_text: str) -> Path:
    """Write a NuGet nuspec fixture at its flat-container path."""
    package_id = package.lower()
    normalized_version = normalize_nuget_version(version)
    destination = (
        root / "packages" / package_id / normalized_version
        / f"{package_id}.nuspec"
    )
    destination.parent.mkdir(parents=True, exist_ok=True)
    destination.write_text(xml_text, encoding="utf-8")
    return destination


def sample_nuspec(package="Demo", version="1.2.3"):
    """Return sample package metadata containing grouped dependencies."""
    return f'''<?xml version="1.0" encoding="utf-8"?>
<package xmlns="http://schemas.microsoft.com/packaging/2013/05/nuspec.xsd">
  <metadata>
    <id>{package}</id><version>{version}</version>
    <dependencies>
      <group targetFramework="net8.0">
        <dependency id="Newtonsoft.Json" version="[13.0.1, 14.0.0)" />
        <dependency id="Utility.Core" version="2.5.0" />
      </group>
      <group targetFramework="netstandard2.0">
        <dependency id="System.Text.Json" version="[8.0.0, )" />
      </group>
      <dependency id="Plain.Dependency" version="1.0.0" />
    </dependencies>
  </metadata>
</package>'''


def write_package_versions(root, package, versions):
    """Write a NuGet flat-container version index for one package."""
    index_path = root / "packages" / package / "index.json"
    index_path.parent.mkdir(parents=True, exist_ok=True)
    index_path.write_text(
        json.dumps({"versions": versions}),
        encoding="utf-8",
    )


def create_nuget_cycle_fixture(root):
    """Create a local NuGet V3 feed containing a transitive version cycle."""
    make_service_index(root)
    write_package_versions(root, "a", ["1.0.0", "1.1.0"])
    write_package_versions(root, "b", ["2.0.0"])
    packages = [
        ("Root", "1.0.0", '<dependency id="A" version="[1.0.0, 2.0.0)" />'),
        ("A", "1.0.0", ""),
        ("A", "1.1.0", '<dependency id="B" version="[2.0.0]" />'),
        ("B", "2.0.0", '<dependency id="A" version="[1.0.0, 2.0.0)" />'),
    ]
    for package, version, dependencies in packages:
        xml = (
            f"<package><metadata><id>{package}</id><version>{version}</version>"
            f"<dependencies>{dependencies}</dependencies></metadata></package>"
        )
        write_nuspec(root, package, version, xml)


def start_repository_server(root):
    """Start a local HTTP server that exposes the supplied package feed."""
    handler = lambda *args, **kwargs: QuietHandler(
        *args,
        directory=str(root),
        **kwargs,
    )
    server = http.server.ThreadingHTTPServer(("127.0.0.1", 0), handler)
    thread = threading.Thread(target=server.serve_forever, daemon=True)
    thread.start()
    return server, thread


def repository_service_url(server):
    """Return the local NuGet V3 service index URL for an HTTP server."""
    return f"http://127.0.0.1:{server.server_port}/index.json"


def stop_repository_server(server, thread):
    """Stop a local HTTP server and wait briefly for its worker thread."""
    server.shutdown()
    server.server_close()
    thread.join(timeout=2)


