class VisualizationTests(unittest.TestCase):
    """Test D2 and SVG visualization."""

    def _graph(self, fixture_name: str, package: str = "A"):
        """Build a dependency graph from a named fixture."""
        args = build_parser().parse_args(
            [
                "--package", package,
                "--repository", str(GRAPH_FIXTURES / fixture_name),
                "--test-repo-mode", "on",
                "--version", "1.0.0",
            ]
        )
        from depgraph.graph import build_test_dependency_graph
        return build_test_dependency_graph(create_configuration(args))

    def test_graph_to_d2_contains_shapes_and_oriented_edges(self):
        """Test that graph to d2 contains shapes and oriented edges."""
        graph = self._graph("chain.json")
        source = graph_to_d2(graph)
        self.assertIn("direction: right", source)
        self.assertIn('pkg_0: "A (root)"', source)
        self.assertIn('pkg_0 -> pkg_1', source)
        self.assertIn('pkg_1 -> pkg_2', source)
        self.assertIn("shape: rectangle", source)

    def test_graph_to_d2_highlights_cycle_nodes_and_edges(self):
        """Test that graph to d2 highlights cycle nodes and edges."""
        source = graph_to_d2(self._graph("cycle.json"))
        self.assertIn('style.fill: "#FEE2E2"', source)
        self.assertIn('style.stroke: "#DC2626"', source)
        self.assertIn('pkg_2 -> pkg_0', source)

    def test_render_dependency_graph_writes_d2_and_valid_svg(self):
        """Test that render dependency graph writes d2 and valid svg."""
        graph = self._graph("branching.json")
        with tempfile.TemporaryDirectory() as temp_dir:
            output = Path(temp_dir) / "branching.svg"
            result = render_dependency_graph(graph, output, d2_executable="")
            self.assertTrue(result.d2_file.is_file())
            self.assertTrue(result.svg_file.is_file())
            self.assertEqual(result.d2_file.suffix, ".d2")
            self.assertEqual(result.svg_file.suffix, ".svg")
            self.assertIn("builtin-svg-fallback", result.renderer)

            root = ET.parse(result.svg_file).getroot()
            self.assertTrue(root.tag.endswith("svg"))
            namespace = {"svg": "http://www.w3.org/2000/svg"}
            node_rectangles = root.findall('.//svg:rect[@rx="10"]', namespace)
            edge_query = './/svg:g[@fill="none"]/svg:path'
            edge_paths = root.findall(edge_query, namespace)
            self.assertEqual(len(node_rectangles), len(graph.adjacency))
            self.assertEqual(len(edge_paths), graph.edge_count)

    def test_render_dependency_graph_marks_cycle_edges_in_svg(self):
        """Test that render dependency graph marks cycle edges in svg."""
        graph = self._graph("cycle.json")
        with tempfile.TemporaryDirectory() as temp_dir:
            output = Path(temp_dir) / "cycle.svg"
            render_dependency_graph(graph, output, d2_executable="")
            tree = ET.parse(output)
            namespace = {"svg": "http://www.w3.org/2000/svg"}
            cycle_query = './/svg:path[@stroke="#DC2626"]'
            cycle_paths = tree.findall(cycle_query, namespace)
            self.assertGreaterEqual(len(cycle_paths), 3)

    def test_render_dependency_graph_can_call_d2_cli_when_available(self):
        """Test that render dependency graph can call d2 cli when available."""
        from unittest.mock import patch
        from subprocess import CompletedProcess

        graph = self._graph("chain.json")
        with tempfile.TemporaryDirectory() as temp_dir:
            output = Path(temp_dir) / "chain.svg"

            def fake_run(command, **kwargs):
                """Write SVG output to simulate a successful compiler run."""
                Path(command[-1]).write_text(
                    '<svg xmlns="http://www.w3.org/2000/svg"></svg>',
                    encoding="utf-8",
                )
                return CompletedProcess(command, 0, "", "")

            which_target = "depgraph.visualization.shutil.which"
            run_target = "depgraph.visualization.subprocess.run"
            with patch(which_target, return_value="/usr/bin/d2"), patch(
                run_target, side_effect=fake_run
            ) as mocked_run:
                result = render_dependency_graph(graph, output)
            self.assertEqual(result.renderer, "d2-cli")
            self.assertTrue(output.is_file())
            mocked_run.assert_called_once()

