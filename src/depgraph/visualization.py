"""D2 serialization and SVG rendering for dependency graphs."""

from __future__ import annotations

import json
import re
import shutil
import subprocess
import xml.etree.ElementTree as ET
from collections import deque
from dataclasses import dataclass
from pathlib import Path

from .models import (
    DependencyGraph,
    GraphVisualizationError,
    PackageNode,
    VisualizationResult,
)

SVG_NAMESPACE = "http://www.w3.org/2000/svg"
SVG_NODE_MIN_WIDTH = 220
SVG_NODE_MAX_WIDTH = 380
SVG_NODE_HEIGHT = 76
SVG_MARGIN_X = 64
SVG_MARGIN_Y = 120
SVG_COLUMN_GAP = 100
SVG_ROW_GAP = 118
SVG_RIGHT_PADDING = 100
SVG_BOTTOM_PADDING = 54
SVG_TITLE_Y = 38
SVG_SUBTITLE_Y = 61
SVG_TEXT_OFFSET_X = 16
SVG_LINE_HEIGHT = 18
SVG_LABEL_MAX_CHARS = 34
SVG_RENDER_TIMEOUT_SECONDS = 120
FIRST_INDEX = 0
SUCCESS_EXIT_STATUS = 0

ROOT_FILL = "#DBEAFE"
ROOT_STROKE = "#2563EB"
NODE_FILL = "#F3F4F6"
NODE_STROKE = "#6B7280"
CYCLE_FILL = "#FEE2E2"
CYCLE_STROKE = "#DC2626"


@dataclass(frozen=True)
class SvgLayout:
    """Calculated positions and canvas dimensions for an SVG graph."""

    positions: dict[PackageNode, tuple[float, float]]
    ranks: dict[PackageNode, int]
    width: int
    height: int
    node_width: int
    node_height: int


def _d2_quote(value: str) -> str:
    """Return a string escaped for a D2 quoted-string literal."""
    return json.dumps(value, ensure_ascii=False)


def _cycle_markings(
    graph: DependencyGraph,
) -> tuple[set[PackageNode], set[tuple[PackageNode, PackageNode]]]:
    """Collect vertices and edges that belong to detected DFS cycles."""
    cycle_nodes: set[PackageNode] = set()
    cycle_edges: set[tuple[PackageNode, PackageNode]] = set()
    for cycle in graph.cycles:
        cycle_nodes.update(cycle[:-1])
        cycle_edges.update(zip(cycle, cycle[1:]))
    return cycle_nodes, cycle_edges


def _d2_node_style(
    node: PackageNode,
    root: PackageNode,
    cycle_nodes: set[PackageNode],
) -> tuple[str, str]:
    """Select fill and outline colors for one D2 graph node."""
    if node in cycle_nodes:
        return CYCLE_FILL, CYCLE_STROKE
    if node == root:
        return ROOT_FILL, ROOT_STROKE
    return NODE_FILL, NODE_STROKE


def _d2_node_lines(
    node: PackageNode,
    root: PackageNode,
    identifier: str,
    cycle_nodes: set[PackageNode],
) -> list[str]:
    """Serialize a single node and its visual styling into D2 lines."""
    label = node.label + (" (root)" if node == root else "")
    fill, stroke = _d2_node_style(node, root, cycle_nodes)
    return [
        f"{identifier}: {_d2_quote(label)} {{",
        "  shape: rectangle",
        f"  style.fill: {_d2_quote(fill)}",
        f"  style.stroke: {_d2_quote(stroke)}",
        "  style.border-radius: 8",
        '  style.font-color: "#111827"',
        "}",
        "",
    ]


def _d2_edge_lines(
    source: PackageNode,
    target: PackageNode,
    identifiers: dict[PackageNode, str],
    cycle_edges: set[tuple[PackageNode, PackageNode]],
) -> list[str]:
    """Serialize an edge, highlighting it when it closes a detected cycle."""
    edge = (source, target)
    link = f"{identifiers[source]} -> {identifiers[target]}"
    if edge not in cycle_edges:
        return [link]
    return [
        f"{link}: {{",
        f'  style.stroke: "{CYCLE_STROKE}"',
        "  style.stroke-width: 2",
        "}",
    ]


def graph_to_d2(graph: DependencyGraph) -> str:
    """Serialize the reachable dependency graph into D2 source text."""
    nodes = list(graph.adjacency)
    if not nodes:
        raise GraphVisualizationError("невозможно визуализировать пустой граф")

    root = nodes[FIRST_INDEX]
    identifiers = {
        node: f"pkg_{index}" for index, node in enumerate(nodes)
    }
    cycle_nodes, cycle_edges = _cycle_markings(graph)
    lines = [
        "# Dependency graph generated by dependency-graph-cli",
        "# Arrow direction: package -> dependency",
        "direction: right",
        "",
    ]
    for node in nodes:
        lines.extend(
            _d2_node_lines(node, root, identifiers[node], cycle_nodes)
        )
    for source, dependencies in graph.adjacency.items():
        for target in dependencies:
            lines.extend(
                _d2_edge_lines(source, target, identifiers, cycle_edges)
            )
    return "\n".join(lines).rstrip() + "\n"


def _svg_element(
    parent: ET.Element,
    tag: str,
    attributes: dict[str, str] | None = None,
    text: str | None = None,
) -> ET.Element:
    """Append an SVG element to its parent and return the new element."""
    element = ET.SubElement(
        parent,
        f"{{{SVG_NAMESPACE}}}{tag}",
        attributes or {},
    )
    element.text = text
    return element


def _label_lines(
    node: PackageNode,
    is_root: bool,
    max_chars: int = SVG_LABEL_MAX_CHARS,
) -> list[str]:
    """Wrap long package labels without splitting short punctuation groups."""
    label = node.label + (" (root)" if is_root else "")
    if len(label) <= max_chars:
        return [label]
    words = re.split(r"([.@/_-])", label)
    lines: list[str] = []
    current = ""
    for word in words:
        if not word:
            continue
        if current and len(current) + len(word) > max_chars:
            lines.append(current)
            current = word
        else:
            current += word
        current = _split_long_label_tokens(current, max_chars, lines)
    if current:
        lines.append(current)
    return lines or [label[:max_chars]]


def _split_long_label_tokens(
    value: str,
    max_chars: int,
    lines: list[str],
) -> str:
    """Split a single unusually long label token into bounded text lines."""
    while len(value) > max_chars:
        lines.append(value[:max_chars])
        value = value[max_chars:]
    return value


def _rank_nodes(graph: DependencyGraph) -> dict[PackageNode, int]:
    """Assign breadth-first ranks for left-to-right graph placement."""
    root = next(iter(graph.adjacency))
    ranks = {root: FIRST_INDEX}
    pending = deque([root])
    while pending:
        source = pending.popleft()
        next_rank = ranks[source] + 1
        for target in graph.adjacency.get(source, []):
            if target not in ranks:
                ranks[target] = next_rank
                pending.append(target)
    return ranks


def _node_layers(
    nodes: list[PackageNode],
    ranks: dict[PackageNode, int],
) -> dict[int, list[PackageNode]]:
    """Group graph nodes by their breadth-first rank."""
    layers: dict[int, list[PackageNode]] = {}
    for node in nodes:
        rank = ranks.get(node, FIRST_INDEX)
        layers.setdefault(rank, []).append(node)
    return layers


def _node_width(nodes: list[PackageNode]) -> int:
    """Calculate a bounded node width from the longest package label."""
    label_width = max(len(node.label) for node in nodes) * 8 + 48
    return min(SVG_NODE_MAX_WIDTH, max(SVG_NODE_MIN_WIDTH, label_width))


def _create_positions(
    layers: dict[int, list[PackageNode]],
    column_gap: int,
) -> dict[PackageNode, tuple[float, float]]:
    """Assign a two-dimensional position to every node in its rank layer."""
    positions: dict[PackageNode, tuple[float, float]] = {}
    for rank, layer in layers.items():
        for index, node in enumerate(layer):
            x = SVG_MARGIN_X + rank * column_gap
            y = SVG_MARGIN_Y + index * SVG_ROW_GAP
            positions[node] = (x, y)
    return positions


def _calculate_layout(graph: DependencyGraph) -> SvgLayout:
    """Calculate positions and canvas size for the built-in SVG renderer."""
    nodes = list(graph.adjacency)
    if not nodes:
        raise GraphVisualizationError("невозможно визуализировать пустой граф")
    ranks = _rank_nodes(graph)
    layers = _node_layers(nodes, ranks)
    node_width = _node_width(nodes)
    column_gap = node_width + SVG_COLUMN_GAP
    max_rank = max(layers)
    max_layer_size = max(len(layer) for layer in layers.values())
    width = (
        SVG_MARGIN_X * 2
        + max_rank * column_gap
        + node_width
        + SVG_RIGHT_PADDING
    )
    height = (
        SVG_MARGIN_Y * 2
        + (max_layer_size - 1) * SVG_ROW_GAP
        + SVG_NODE_HEIGHT
        + SVG_BOTTOM_PADDING
    )
    positions = _create_positions(layers, column_gap)
    return SvgLayout(
        positions,
        ranks,
        width,
        height,
        node_width,
        SVG_NODE_HEIGHT,
    )


def _add_svg_markers(root: ET.Element) -> None:
    """Create the standard and cycle arrow markers for SVG edges."""
    definitions = _svg_element(root, "defs")
    markers = (
        ("arrowhead", "#64748B"),
        ("arrowhead-cycle", CYCLE_STROKE),
    )
    for marker_id, color in markers:
        marker = _svg_element(
            definitions,
            "marker",
            {
                "id": marker_id,
                "markerWidth": "10",
                "markerHeight": "8",
                "refX": "9",
                "refY": "4",
                "orient": "auto",
                "markerUnits": "strokeWidth",
            },
        )
        _svg_element(
            marker,
            "path",
            {"d": "M0,0 L10,4 L0,8 z", "fill": color},
        )


def _add_svg_title(
    root: ET.Element,
    graph: DependencyGraph,
    layout: SvgLayout,
) -> None:
    """Add a title and graph summary to the SVG canvas."""
    root_node = next(iter(graph.adjacency))
    _svg_element(
        root,
        "text",
        {
            "x": str(SVG_MARGIN_X),
            "y": str(SVG_TITLE_Y),
            "font-family": "Arial, sans-serif",
            "font-size": "22",
            "font-weight": "700",
            "fill": "#111827",
        },
        f"Dependency graph — {root_node.label}",
    )
    _svg_element(
        root,
        "text",
        {
            "x": str(SVG_MARGIN_X),
            "y": str(SVG_SUBTITLE_Y),
            "font-family": "Arial, sans-serif",
            "font-size": "12",
            "fill": "#6B7280",
        },
        f"{len(graph.adjacency)} packages · {graph.edge_count} dependencies",
    )


def _add_svg_accessibility(
    root: ET.Element,
    graph: DependencyGraph,
) -> None:
    """Add accessible title and description elements to the SVG."""
    root_node = next(iter(graph.adjacency))
    _svg_element(
        root,
        "title",
        {"id": "diagram-title"},
        f"Dependency graph: {root_node.label}",
    )
    _svg_element(
        root,
        "desc",
        {"id": "diagram-desc"},
        "Arrows point from a package to its dependency.",
    )


def _add_svg_background(root: ET.Element, layout: SvgLayout) -> None:
    """Add a white background rectangle matching the SVG canvas size."""
    _svg_element(
        root,
        "rect",
        {
            "x": "0",
            "y": "0",
            "width": str(layout.width),
            "height": str(layout.height),
            "fill": "#FFFFFF",
        },
    )


def _create_svg_root(
    graph: DependencyGraph,
    layout: SvgLayout,
) -> ET.Element:
    """Create the SVG root, accessibility labels and common definitions."""
    ET.register_namespace("", SVG_NAMESPACE)
    dimensions = {
        "width": str(layout.width),
        "height": str(layout.height),
        "viewBox": f"0 0 {layout.width} {layout.height}",
        "role": "img",
        "aria-labelledby": "diagram-title diagram-desc",
        "version": "1.1",
    }
    root = ET.Element(f"{{{SVG_NAMESPACE}}}svg", dimensions)
    _add_svg_accessibility(root, graph)
    _add_svg_markers(root)
    _add_svg_background(root, layout)
    _add_svg_title(root, graph, layout)
    return root


def _edge_path(
    source: PackageNode,
    target: PackageNode,
    layout: SvgLayout,
) -> str:
    """Calculate a curved SVG path for one directed dependency edge."""
    sx, sy = layout.positions[source]
    tx, ty = layout.positions[target]
    source_x = sx + layout.node_width
    source_y = sy + layout.node_height / 2
    target_y = ty + layout.node_height / 2
    if source == target:
        return _self_loop_path(sx, sy, layout.node_width)
    if layout.ranks[source] >= layout.ranks[target]:
        return _back_edge_path(source_x, source_y, tx, target_y, sy, ty)
    return _forward_edge_path(source_x, source_y, tx, target_y)


def _self_loop_path(x: float, y: float, width: int) -> str:
    """Return a cubic path that loops back into the same node."""
    start_x = x + width * 0.72
    control_x = x + width + 70
    return (
        f"M {start_x:.1f} {y:.1f} "
        f"C {control_x:.1f} {y - 45:.1f}, "
        f"{control_x:.1f} {y + 5:.1f}, "
        f"{start_x:.1f} {y + 8:.1f}"
    )


def _back_edge_path(
    source_x: float,
    source_y: float,
    target_x: float,
    target_y: float,
    source_top: float,
    target_top: float,
) -> str:
    """Route a backward edge above its source and target nodes."""
    outside_y = min(source_top, target_top) - 34
    return (
        f"M {source_x:.1f} {source_y:.1f} "
        f"C {source_x + 45:.1f} {outside_y:.1f}, "
        f"{target_x - 45:.1f} {outside_y:.1f}, "
        f"{target_x:.1f} {target_y:.1f}"
    )


def _forward_edge_path(
    source_x: float,
    source_y: float,
    target_x: float,
    target_y: float,
) -> str:
    """Route a forward edge between columns using a cubic curve."""
    middle_x = (source_x + target_x) / 2
    return (
        f"M {source_x:.1f} {source_y:.1f} "
        f"C {middle_x:.1f} {source_y:.1f}, "
        f"{middle_x:.1f} {target_y:.1f}, "
        f"{target_x:.1f} {target_y:.1f}"
    )


def _draw_svg_edges(
    root: ET.Element,
    graph: DependencyGraph,
    layout: SvgLayout,
    cycle_edges: set[tuple[PackageNode, PackageNode]],
) -> None:
    """Draw all graph edges with cycle-specific colors and arrowheads."""
    group = _svg_element(
        root,
        "g",
        {"fill": "none", "stroke-linecap": "round"},
    )
    for source, dependencies in graph.adjacency.items():
        for target in dependencies:
            edge = (source, target)
            is_cycle = edge in cycle_edges
            color = CYCLE_STROKE if is_cycle else "#64748B"
            marker = "arrowhead-cycle" if is_cycle else "arrowhead"
            _svg_element(
                group,
                "path",
                {
                    "d": _edge_path(source, target, layout),
                    "stroke": color,
                    "stroke-width": "2.2",
                    "marker-end": f"url(#{marker})",
                },
            )


def _node_style(
    node: PackageNode,
    root: PackageNode,
    cycle_nodes: set[PackageNode],
) -> tuple[str, str]:
    """Select an SVG fill and outline for a graph vertex."""
    if node in cycle_nodes:
        return "#FEF2F2", CYCLE_STROKE
    if node == root:
        return "#EFF6FF", ROOT_STROKE
    return "#F8FAFC", "#94A3B8"


def _draw_svg_node(
    group: ET.Element,
    node: PackageNode,
    root: PackageNode,
    layout: SvgLayout,
    cycle_nodes: set[PackageNode],
) -> None:
    """Draw one rounded node and its wrapped package label."""
    x, y = layout.positions[node]
    fill, stroke = _node_style(node, root, cycle_nodes)
    attributes = {
        "x": f"{x:.1f}",
        "y": f"{y:.1f}",
        "width": str(layout.node_width),
        "height": str(layout.node_height),
        "rx": "10",
        "fill": fill,
        "stroke": stroke,
        "stroke-width": "2",
    }
    _svg_element(group, "rect", attributes)
    _draw_node_label(group, node, root, x, y, layout.node_height)


def _draw_node_label(
    group: ET.Element,
    node: PackageNode,
    root: PackageNode,
    x: float,
    y: float,
    node_height: int,
) -> None:
    """Draw package text lines centered vertically inside a node."""
    lines = _label_lines(node, node == root)
    start_y = y + (node_height - len(lines) * SVG_LINE_HEIGHT) / 2 + 14
    text = _svg_element(
        group,
        "text",
        {
            "x": f"{x + SVG_TEXT_OFFSET_X:.1f}",
            "y": f"{start_y:.1f}",
            "font-size": "14",
            "font-weight": "600",
            "fill": "#1F2937",
        },
    )
    for index, line in enumerate(lines):
        dy = "0" if index == FIRST_INDEX else str(SVG_LINE_HEIGHT)
        _svg_element(
            text,
            "tspan",
            {"x": f"{x + SVG_TEXT_OFFSET_X:.1f}", "dy": dy},
            line,
        )


def _draw_svg_nodes(
    root_element: ET.Element,
    graph: DependencyGraph,
    layout: SvgLayout,
    cycle_nodes: set[PackageNode],
) -> None:
    """Draw every package node over the SVG edge layer."""
    root_node = next(iter(graph.adjacency))
    group = _svg_element(
        root_element,
        "g",
        {"font-family": "Arial, sans-serif"},
    )
    for node in graph.adjacency:
        _draw_svg_node(group, node, root_node, layout, cycle_nodes)


def render_svg_builtin(graph: DependencyGraph, svg_file: str | Path) -> None:
    """Render a standalone SVG using only Python's standard library."""
    layout = _calculate_layout(graph)
    cycle_nodes, cycle_edges = _cycle_markings(graph)
    root = _create_svg_root(graph, layout)
    _draw_svg_edges(root, graph, layout, cycle_edges)
    _draw_svg_nodes(root, graph, layout, cycle_nodes)
    output_path = Path(svg_file)
    try:
        payload = ET.tostring(root, encoding="utf-8", xml_declaration=True)
        output_path.write_bytes(payload)
    except OSError as exc:
        raise GraphVisualizationError(
            f"не удалось сохранить SVG-файл {output_path}: {exc}"
        ) from exc


def _validate_svg_path(svg_file: str | Path) -> Path:
    """Validate the SVG suffix and existing output directory."""
    svg_path = Path(svg_file).expanduser().resolve()
    if svg_path.suffix.lower() != ".svg":
        raise GraphVisualizationError(
            "выходной файл визуализации должен иметь расширение .svg"
        )
    if not svg_path.parent.is_dir():
        raise GraphVisualizationError(
            f"каталог для SVG не существует: {svg_path.parent}"
        )
    return svg_path


def _write_d2_source(svg_path: Path, graph: DependencyGraph) -> Path:
    """Write the D2 source next to the selected SVG output path."""
    d2_path = svg_path.with_suffix(".d2")
    try:
        d2_path.write_text(graph_to_d2(graph), encoding="utf-8")
    except OSError as exc:
        raise GraphVisualizationError(
            f"не удалось сохранить D2-файл {d2_path}: {exc}"
        ) from exc
    return d2_path


def _run_d2_compiler(executable: str, d2_path: Path, svg_path: Path) -> None:
    """Run D2 CLI to compile a D2 source file into SVG."""
    try:
        completed = subprocess.run(
            [executable, str(d2_path), str(svg_path)],
            check=False,
            capture_output=True,
            text=True,
            timeout=SVG_RENDER_TIMEOUT_SECONDS,
        )
    except (OSError, subprocess.TimeoutExpired) as exc:
        raise GraphVisualizationError(
            f"не удалось запустить компилятор D2: {exc}"
        ) from exc
    if completed.returncode != SUCCESS_EXIT_STATUS:
        detail = (completed.stderr or completed.stdout or "ошибка D2").strip()
        raise GraphVisualizationError(
            f"компилятор D2 завершился с ошибкой: {detail}"
        )
    if not svg_path.is_file():
        raise GraphVisualizationError(
            "компилятор D2 завершился без создания SVG-файла"
        )


def render_dependency_graph(
    graph: DependencyGraph,
    svg_file: str | Path,
    *,
    d2_executable: str | None = None,
) -> VisualizationResult:
    """Save D2 source and render SVG through D2 CLI or built-in fallback."""
    svg_path = _validate_svg_path(svg_file)
    d2_path = _write_d2_source(svg_path, graph)
    executable = shutil.which("d2") if d2_executable is None else d2_executable
    if executable:
        _run_d2_compiler(executable, d2_path, svg_path)
        renderer = "d2-cli"
    else:
        render_svg_builtin(graph, svg_path)
        renderer = "builtin-svg-fallback (D2 CLI not installed)"
    return VisualizationResult(d2_path, svg_path, renderer)
